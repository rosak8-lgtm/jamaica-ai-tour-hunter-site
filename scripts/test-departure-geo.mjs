import assert from "node:assert/strict";
import fs from "node:fs";
import worker,{cityHint} from "../edge/departure-city.mjs";
import "./departure-geo.js";
const geo=globalThis.JamaicaDepartureGeo;
const page=fs.readFileSync("index.html","utf8");
const choices=[...page.match(/<select id="departure"[^>]*>(.*?)<\/select>/s)[1].matchAll(/<option value="([^"]+)"/g)].map(x=>x[1]);
assert.equal(choices.length,60);
assert.equal(new Set(choices).size,60);
for(const city of choices){
 const region=city==="Кировск"?"Murmansk":city==="Киров"?"Kirov":city==="Благовещенск"?"Amur":"";
 assert.equal(cityHint({country:"RU",city,region}),city);
}
assert.equal(cityHint({country:"RU",city:"Moscow"}),"Москва");
assert.equal(cityHint({country:"RU",city:"Krasnoyarsk"}),"Красноярск");
assert.equal(cityHint({country:"RU",city:"St. Petersburg"}),"Санкт-Петербург");
assert.equal(cityHint({country:"GE",city:"Tbilisi"}),null);
assert.equal(cityHint({country:"RU",city:"Kirovsk",region:"Leningrad"}),null);
assert.equal(cityHint({country:"RU",city:"unknown"}),null);
const req=(origin,cf,method="GET",path="/api/departure-city")=>({url:"https://geo.example"+path,method,headers:new Headers(origin?{Origin:origin}:{}),cf});
const origin="https://rosak8-lgtm.github.io";
const response=await worker.fetch(req(origin,{country:"RU",city:"Moscow",latitude:"1",longitude:"2"}));
assert.equal(response.status,200);
assert.equal(response.headers.get("access-control-allow-origin"),origin);
assert.match(response.headers.get("cache-control"),/no-store/);
assert.deepEqual(await response.json(),{schema:"jamaica.departure-hint.v1",city:"Москва",source:"IP_APPROXIMATE"});
assert.equal((await worker.fetch(req("https://else.example",{}))).status,403);
assert.equal((await worker.fetch(req(origin,{},"POST"))).status,405);
assert.equal((await worker.fetch(req(origin,{},"GET","/else"))).status,404);
const config={schema:"jamaica.departure-geo-config.v1",enabled:true,endpoint:"https://jamaica-city-geo.example.workers.dev/api/departure-city"};
assert.equal(geo.endpoint(config),config.endpoint);
for(const endpoint of ["https://example.com/api/departure-city","http://jamaica-city-geo.example.workers.dev/api/departure-city","https://jamaica-city-geo.example.workers.dev/api/departure-city?x=1","https://a.b.workers.dev@evil.example/api/departure-city"])assert.equal(geo.endpoint({...config,endpoint}),null);
const hint={schema:"jamaica.departure-hint.v1",source:"IP_APPROXIMATE",city:"Москва"};
assert.equal(geo.validHint(hint,choices),"Москва");
assert.equal(geo.validHint({...hint,city:"Тбилиси"},choices),null);
let saved=null,applied=[],status=[],calls=[];
const storage={getItem:()=>saved,setItem:(k,v)=>{saved=v;}};
const common={select:{options:choices.map(value=>({value}))},storage,apply:v=>applied.push(v),status:v=>status.push(v)};
const fetcher=async url=>{calls.push(url);return {ok:true,json:async()=>url.startsWith(".")?config:hint};};
await geo.start({...common,fetcher});
assert.deepEqual(applied,["Москва"]);
assert.equal(saved,null);
geo.remember(storage,"Иркутск",choices);
applied=[];calls=[];
await geo.start({...common,fetcher});
assert.deepEqual(applied,["Иркутск"]);assert.equal(calls.length,0);
saved=null;applied=[];calls=[];
let manual=false;
await geo.start({...common,canAuto:()=>!manual,fetcher:async url=>{if(!url.startsWith("."))manual=true;return fetcher(url);}});
assert.deepEqual(applied,[]);
calls=[];
await geo.start({...common,fetcher:async url=>{calls.push(url);return {ok:true,json:async()=>({...config,enabled:false})};}});
assert.equal(calls.length,1);
await geo.start({...common,fetcher:async()=>{throw Error("offline");}});
assert.deepEqual(applied,[]);
